"""Decomposed ROS 2 CDR generator section."""

from __future__ import annotations

from ._shared import *

def generate_deserializers(schemas: list[Schema]) -> str:
    """Generate the C# per-schema direct CDR deserializer source."""

    lines: list[str] = [
        "// Copyright (c) 2026 Jianbin Liu and Unity2Foxglove contributors.",
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Module: Runtime/Schemas/Ros2Msg/Generated",
        "// Purpose: Generated direct ROS 2 CDR deserializers for official Foxglove .msg schemas.",
        "// Generated by Scripts/schema/generate_ros2_cdr_serializers.py.",
        "",
        "using System;",
        "using System.IO;",
        "",
        f"namespace {CSHARP_NAMESPACE}",
        "{",
        "    /// <summary>Generated direct ROS 2 CDR deserializers for official Foxglove .msg schemas.</summary>",
        "    public static class Ros2CdrGeneratedDeserializers",
        "    {",
        "        private static global::Google.Protobuf.WellKnownTypes.Timestamp ReadTime(Ros2CdrReader reader)",
        "        {",
        "            if (reader == null)",
        "                throw new ArgumentNullException(nameof(reader));",
        "",
        "            var seconds = reader.ReadInt32();",
        "            var nanos = reader.ReadUInt32();",
        "            if (nanos > 999_999_999U)",
        "                throw new InvalidDataException(\"ROS 2 Time nanoseconds must be less than 1e9.\");",
        "            return new global::Google.Protobuf.WellKnownTypes.Timestamp { Seconds = seconds, Nanos = (int)nanos };",
        "        }",
        "",
        "        private static global::Google.Protobuf.WellKnownTypes.Duration ReadDuration(Ros2CdrReader reader)",
        "        {",
        "            if (reader == null)",
        "                throw new ArgumentNullException(nameof(reader));",
        "",
        "            var seconds = reader.ReadInt32();",
        "            var nanos = reader.ReadUInt32();",
        "            if (nanos > 999_999_999U)",
        "                throw new InvalidDataException(\"ROS 2 Duration nanoseconds must be less than 1e9.\");",
        "            return new global::Google.Protobuf.WellKnownTypes.Duration { Seconds = seconds, Nanos = (int)nanos };",
        "        }",
        "",
        "        private static global::Foxglove.Point3 ReadProtoPoint(Ros2CdrReader reader)",
        "        {",
        "            if (reader == null)",
        "                throw new ArgumentNullException(nameof(reader));",
        "",
        "            return new global::Foxglove.Point3 { X = reader.ReadFloat64(), Y = reader.ReadFloat64(), Z = reader.ReadFloat64() };",
        "        }",
        "",
        "        private static global::Foxglove.Vector3 ReadProtoVector3(Ros2CdrReader reader)",
        "        {",
        "            if (reader == null)",
        "                throw new ArgumentNullException(nameof(reader));",
        "",
        "            return new global::Foxglove.Vector3 { X = reader.ReadFloat64(), Y = reader.ReadFloat64(), Z = reader.ReadFloat64() };",
        "        }",
        "",
        "        private static global::Foxglove.Quaternion ReadProtoQuaternion(Ros2CdrReader reader)",
        "        {",
        "            if (reader == null)",
        "                throw new ArgumentNullException(nameof(reader));",
        "",
        "            return new global::Foxglove.Quaternion { X = reader.ReadFloat64(), Y = reader.ReadFloat64(), Z = reader.ReadFloat64(), W = reader.ReadFloat64() };",
        "        }",
        "",
        "        private static global::Foxglove.Pose ReadProtoPose(Ros2CdrReader reader)",
        "        {",
        "            if (reader == null)",
        "                throw new ArgumentNullException(nameof(reader));",
        "",
        "            return new global::Foxglove.Pose { Position = ReadProtoVector3(reader), Orientation = ReadProtoQuaternion(reader) };",
        "        }",
        "",
    ]

    for schema in schemas:
        lines.extend(
            [
                f"        public static {schema_type(schema.name)} Deserialize{schema.name}(byte[] payload)",
                "        {",
                "            var reader = new Ros2CdrReader(payload);",
                f"            var message = Read{schema.name}(reader);",
                "            reader.EnsureFullyConsumed();",
                "            return message;",
                "        }",
                "",
            ]
        )

    for schema in schemas:
        lines.extend(
            [
                f"        internal static {schema_type(schema.name)} Read{schema.name}(Ros2CdrReader reader)",
                "        {",
                "            if (reader == null)",
                "                throw new ArgumentNullException(nameof(reader));",
                f"            var message = new {schema_type(schema.name)}();",
                "",
            ]
        )
        for field in schema.fields:
            for line in reader_for_field(field):
                lines.append("            " + line)
        lines.extend(["            return message;", "        }", ""])

    lines.extend(["    }", "}"])
    return "\n".join(lines) + "\n"


