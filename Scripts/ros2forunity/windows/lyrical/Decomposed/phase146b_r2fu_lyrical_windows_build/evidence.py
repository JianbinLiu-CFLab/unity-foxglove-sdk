from __future__ import annotations

def write_evidence(
    evidence_path: pathlib.Path,
    *,
    verdict: str,
    log_file: pathlib.Path,
    repo_root: pathlib.Path,
    work_root: pathlib.Path,
    temp_root: pathlib.Path,
    ros2_root: pathlib.Path,
    vs_dev_cmd: pathlib.Path | None,
    effective_generator: str,
    no_build: bool,
) -> None:
    """Write the local Phase146B evidence note."""

    lines = [
        "---",
        'title: "Phase146B R2FU Lyrical Windows Build Toolchain Closure Evidence"',
        "tags:",
        "  - developer",
        "  - phase146b",
        "  - ros2-for-unity",
        "  - lyrical",
        "  - windows",
        "status: blocked" if verdict != "BUILD_ORCHESTRATOR_GREEN" else "status: green",
        f"updated: {_dt.date.today().isoformat()}",
        "---",
        "",
        "# Phase146B R2FU Lyrical Windows Build Toolchain Closure Evidence",
        "",
        "## Verdict",
        "",
        "```text",
        verdict,
        "```",
        "",
        "Python orchestrator was used. No project-owned PowerShell wrapper was created.",
        "",
        "## Paths",
        "",
        "```text",
        f"RepoRoot: {repo_root}",
        f"WorkRoot: {work_root}",
        f"Checkout: {work_root / CHECKOUT_DIR_NAME}",
        f"TempRoot: {temp_root}",
        f"Ros2Root: {ros2_root}",
        f"VsDevCmd: {vs_dev_cmd if vs_dev_cmd else 'not resolved'}",
        f"EffectiveGenerator: {effective_generator}",
        f"Log: {log_file}",
        "NoBuild: " + ("true" if no_build else "false"),
        "```",
        "",
        "## Required Diagnostics",
        "",
        "The log records:",
        "",
        "```text",
        "where python",
        "where pip",
        "where colcon",
        "where cmake",
        "where ninja",
        "where msbuild",
        "where cl",
        "catkin_pkg import check",
        "cl tiny compile check",
        "```",
        "",
        "## Boundary",
        "",
        "Phase146B does not import any partial R2FU asset into Unity.",
        "",
        "Live Unity/RViz2 acceptance remains a separate gate after a complete Lyrical runtime package exists.",
        "",
    ]
    evidence_path.parent.mkdir(parents=True, exist_ok=True)
    evidence_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
